class GPT(nn.Module):
    """Decoder-only transformer. Small, plain, and readable on purpose."""

    def __init__(self, config: GPTConfig):
        super().__init__()
        self.config = config

        self.transformer = nn.ModuleDict(
            dict(
                wte=nn.Embedding(config.vocab_size, config.n_embd),  # token embedding
                wpe=nn.Embedding(config.block_size, config.n_embd),  # learned positions
                drop=nn.Dropout(config.dropout),
                h=nn.ModuleList([Block(config) for _ in range(config.n_layer)]),
                ln_f=nn.LayerNorm(config.n_embd, bias=config.bias),
            )
        )
        self.lm_head = nn.Linear(config.n_embd, config.vocab_size, bias=False)

        if config.tie_weights:
            # GPT-2 ties the input embedding and the output projection. Lab 2
            # has to shard both halves of a tied weight consistently, which is
            # more interesting than it sounds.
            self.transformer.wte.weight = self.lm_head.weight

        self.apply(self._init_weights)

        # nanoGPT's scaled init for residual projections: without it, the
        # residual stream's variance grows with depth.
        for name, param in self.named_parameters():
            if name.endswith("c_proj.weight"):
                torch.nn.init.normal_(param, mean=0.0, std=0.02 / math.sqrt(2 * config.n_layer))

    @staticmethod
    def _init_weights(module: nn.Module) -> None:
        if isinstance(module, nn.Linear):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                torch.nn.init.zeros_(module.bias)
        elif isinstance(module, nn.Embedding):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)

    def forward(
        self,
        idx: torch.Tensor,
        targets: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor | None]:
        """``idx`` is (B, T) token ids. Returns ``(logits, loss)``.

        When ``targets`` is None the loss is None, and logits are computed for
        every position anyway. nanoGPT optimises that case by only running the
        head on the last position; this file does not, because Lab 2 needs the
        full logit tensor to talk about vocab-parallel cross-entropy.
        """
        device = idx.device
        B, T = idx.shape
        if self.config.block_size < T:
            raise ValueError(f"sequence length {T} exceeds block_size {self.config.block_size}")

        pos = torch.arange(T, dtype=torch.long, device=device)

        tok_emb = self.transformer.wte(idx)  # (B, T, C)
        pos_emb = self.transformer.wpe(pos)  # (T, C), broadcast over batch
        x = self.transformer.drop(tok_emb + pos_emb)

        for block in self.transformer.h:
            x = block(x)
        x = self.transformer.ln_f(x)

        logits = self.lm_head(x)  # (B, T, vocab)

        loss = None
        if targets is not None:
            loss = F.cross_entropy(
                logits.view(-1, logits.size(-1)),
                targets.reshape(-1),
                ignore_index=-1,
            )
        return logits, loss

    # -- utilities ---------------------------------------------------------- #

    def num_params(self, non_embedding: bool = False) -> int:
        """Trainable parameter count.

        ``non_embedding=True`` subtracts the positional table, matching the
        convention most papers use when they quote a model size. The token
        embedding is not subtracted because weight tying makes it part of the
        output head.
        """
        n = sum(p.numel() for p in self.parameters())
        if non_embedding:
            n -= self.transformer.wpe.weight.numel()
        return n

    def flops_per_token(self) -> int:
        """Forward-plus-backward FLOPs per token, the usual ``6N`` estimate.

        Lab 4 uses this for MFU. It ignores attention's quadratic term, which
        is fine at these sequence lengths and stops being fine past a few
        thousand tokens.
        """
        return 6 * self.num_params()

    @torch.no_grad()
    def generate(
        self,
        idx: torch.Tensor,
        max_new_tokens: int,
        temperature: float = 1.0,
        top_k: int | None = None,
    ) -> torch.Tensor:
        """Sample continuations. Present so you can eyeball whether training worked."""
        for _ in range(max_new_tokens):
            idx_cond = idx[:, -self.config.block_size :]
            logits, _ = self(idx_cond)
            logits = logits[:, -1, :] / max(temperature, 1e-8)
            if top_k is not None:
                v, _ = torch.topk(logits, min(top_k, logits.size(-1)))
                logits[logits < v[:, [-1]]] = float("-inf")
            probs = F.softmax(logits, dim=-1)
            idx = torch.cat((idx, torch.multinomial(probs, num_samples=1)), dim=1)
        return idx

    def configure_optimizer(
        self, lr: float = 1e-3, weight_decay: float = 0.1, betas: tuple[float, float] = (0.9, 0.95)
    ) -> torch.optim.Optimizer:
        """AdamW with the usual split: decay matrices, do not decay biases and norms.

        Lab 1B's ledger assumes AdamW with two fp32 moments per parameter, so
        keep this in sync if you change it.
        """
        decay, no_decay = [], []
        for _name, param in self.named_parameters():
            if not param.requires_grad:
                continue
            (decay if param.dim() >= 2 else no_decay).append(param)
        return torch.optim.AdamW(
            [
                {"params": decay, "weight_decay": weight_decay},
                {"params": no_decay, "weight_decay": 0.0},
            ],
            lr=lr,
            betas=betas,
        )
