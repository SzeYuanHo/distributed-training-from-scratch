class CausalSelfAttention(nn.Module):
    """Multi-head causal self-attention, written out longhand.

    Lab 2 shards this by head: ``c_attn`` becomes column-parallel so each rank
    owns whole heads, and ``c_proj`` becomes row-parallel so the per-rank
    partial outputs sum. Whole heads matter. If a head were split across two
    ranks, computing its softmax would need a collective inside the attention
    itself, and the cost model falls apart.
    """

    def __init__(self, config: GPTConfig):
        super().__init__()
        self.n_head = config.n_head
        self.n_embd = config.n_embd
        self.head_dim = config.head_dim
        self.dropout = config.dropout

        # One fused projection producing Q, K and V. Column-parallel in Lab 2.
        self.c_attn = nn.Linear(config.n_embd, 3 * config.n_embd, bias=config.bias)
        # Output projection. Row-parallel in Lab 2.
        self.c_proj = nn.Linear(config.n_embd, config.n_embd, bias=config.bias)

        self.attn_dropout = nn.Dropout(config.dropout)
        self.resid_dropout = nn.Dropout(config.dropout)

        # Lower-triangular mask. Registered as a buffer so it moves with .to()
        # and shows up in state_dict comparisons.
        mask = torch.tril(torch.ones(config.block_size, config.block_size))
        self.register_buffer("causal_mask", mask.view(1, 1, config.block_size, config.block_size))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, T, C = x.shape  # batch, time, channels

        qkv = self.c_attn(x)  # (B, T, 3C)
        q, k, v = qkv.split(self.n_embd, dim=2)  # each (B, T, C)

        # (B, T, C) -> (B, n_head, T, head_dim). The transpose puts heads on the
        # batch side so the matmuls below are per-head.
        q = q.view(B, T, self.n_head, self.head_dim).transpose(1, 2)
        k = k.view(B, T, self.n_head, self.head_dim).transpose(1, 2)
        v = v.view(B, T, self.n_head, self.head_dim).transpose(1, 2)

        # Scaled dot-product attention, spelled out. This is the largest
        # intermediate in the model: (B, n_head, T, T) grows quadratically in T,
        # which is the term the activation-memory formula in memory.py cares about.
        att = (q @ k.transpose(-2, -1)) / math.sqrt(self.head_dim)  # (B, nh, T, T)
        att = att.masked_fill(self.causal_mask[:, :, :T, :T] == 0, float("-inf"))
        att = F.softmax(att, dim=-1)
        att = self.attn_dropout(att)

        y = att @ v  # (B, nh, T, hd)
        y = y.transpose(1, 2).contiguous().view(B, T, C)  # back to (B, T, C)

        return self.resid_dropout(self.c_proj(y))


class MLP(nn.Module):
    """The standard 4x-expansion feed-forward block.

    In Lab 2 ``c_fc`` is column-parallel and ``c_proj`` is row-parallel, in
    that order, and the ordering is the point: the column-parallel layer emits
    activations already sharded along the feature dimension, GELU is elementwise
    so it applies to a shard without any communication, and the row-parallel
    layer consumes the shard directly. One all-reduce for the whole block.
    Reverse the order and you need two.
    """

    def __init__(self, config: GPTConfig):
        super().__init__()
        self.c_fc = nn.Linear(config.n_embd, 4 * config.n_embd, bias=config.bias)
        self.gelu = nn.GELU()
        self.c_proj = nn.Linear(4 * config.n_embd, config.n_embd, bias=config.bias)
        self.dropout = nn.Dropout(config.dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.c_fc(x)  # (B, T, C) -> (B, T, 4C)
        x = self.gelu(x)
        x = self.c_proj(x)  # (B, T, 4C) -> (B, T, C)
        return self.dropout(x)


class Block(nn.Module):
    """Pre-norm transformer block. Two residual streams, two sublayers.

    Lab 3 splits the model at block boundaries, which is why this class is the
    natural unit of a pipeline stage.
    """

    def __init__(self, config: GPTConfig):
        super().__init__()
        self.ln_1 = nn.LayerNorm(config.n_embd, bias=config.bias)
        self.attn = CausalSelfAttention(config)
        self.ln_2 = nn.LayerNorm(config.n_embd, bias=config.bias)
        self.mlp = MLP(config)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = x + self.attn(self.ln_1(x))
        x = x + self.mlp(self.ln_2(x))
        return x


