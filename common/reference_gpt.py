"""FROZEN reference model. Adapted from nanoGPT (MIT, Andrej Karpathy).

    https://github.com/karpathy/nanoGPT

=============================================================================
DO NOT EDIT THIS FILE.
=============================================================================

Every lab compares its output against this model. If Lab 2 changes an
activation function here to make its tensor-parallel version match, the
comparison stops meaning anything and so does the lab. CI hashes this file and
fails the build if it changed; ``python tasks.py freeze-check`` runs the same
check locally.

Labs extend it the way you would extend a third-party library:

* subclass a module and override ``forward``
* build a parallel replacement and load ``state_dict`` from an instance of this
* monkey-patch a layer inside a test, then restore it

That constraint is not bureaucracy. It is what makes "my tensor-parallel GPT
produces the same logits as the reference" a claim worth making.

Design choices, all of them deliberate and all of them costing performance:

* No flash attention. The explicit ``softmax(QK^T / sqrt(d)) V`` is four lines
  you can read, and Lab 2 needs to shard it by head.
* No fused kernels, no ``torch.compile``. Fusion hides where the tensors are.
* Shapes written out in comments at every step, because Lab 2 spends its whole
  life reasoning about which dimension got sharded.
* Weight tying between the embedding and the LM head, as in GPT-2. Lab 2 has
  to handle this: a tied weight sharded by vocab is sharded in both places at
  once.

Presets:

======  =======  ======  ======  =====  =====  ======  ==========
name    n_layer  n_embd  n_head  block  vocab  max_tp  params
======  =======  ======  ======  =====  =====  ======  ==========
tiny    4        128     4       128    72     4       ~0.82 M
small   6        384     8       256    72     8       ~10.77 M
tier2   8        512     8       512    72     8       ~25.52 M
======  =======  ======  ======  =====  =====  ======  ==========

``tiny`` is the default everywhere. It trains to a visibly falling loss on
tiny-shakespeare in about a minute of laptop CPU, and four ranks of it fit in
RAM without thinking about it.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, replace
from typing import Any

import torch
import torch.nn as nn
from torch.nn import functional as F

__all__ = ["GPTConfig", "GPT", "CausalSelfAttention", "MLP", "Block", "PRESETS", "make_model"]

# Default tensor-parallel degree used by direct ``GPTConfig`` construction and
# by ``padded_vocab``. Lab 2's standard checks run at tp=2 and tp=4. Presets
# whose heads, hidden size, and padded vocabulary support tp=8 opt into it
# explicitly rather than making every custom config satisfy that larger degree.
DEFAULT_TP_DEGREE = 4


@dataclass
class GPTConfig:
    """Model shape. Validated on construction so failures happen early.

    The divisibility asserts are the interesting part. A tensor-parallel layer
    splits ``n_embd`` across ranks and attention splits ``n_head`` across ranks,
    so both have to divide evenly. Discovering that at rank 3 of an 8-rank job,
    four layers into a forward pass, is a bad time. Discovering it in the
    constructor is a good time.
    """

    block_size: int = 128
    vocab_size: int = 68  # 65 raw characters, padded for the default max_tp=4
    n_layer: int = 4
    n_head: int = 4
    n_embd: int = 128
    dropout: float = 0.0  # zero by default; see the RNG note below
    bias: bool = True
    tie_weights: bool = True
    max_tp: int = DEFAULT_TP_DEGREE  # highest tensor-parallel degree this config supports

    def __post_init__(self) -> None:
        if self.n_embd % self.n_head != 0:
            raise ValueError(
                f"n_embd ({self.n_embd}) must be divisible by n_head ({self.n_head}); "
                f"head_dim would be {self.n_embd / self.n_head}."
            )
        for name, value in (("n_embd", self.n_embd), ("n_head", self.n_head)):
            if value % self.max_tp != 0:
                raise ValueError(
                    f"{name} ({value}) must be divisible by max_tp ({self.max_tp}), the "
                    f"highest tensor-parallel degree this config claims to support.\n"
                    f"  Column-parallel layers split {name} across ranks, and an uneven "
                    f"split means ranks hold different-sized shards, which every collective "
                    f"in Lab 2 assumes away.\n"
                    f"  Either raise {name} to "
                    f"{value + self.max_tp - value % self.max_tp}, or lower max_tp to a "
                    f"divisor of {value}."
                )
        if self.vocab_size % self.max_tp != 0:
            # tiny-shakespeare has 65 characters, which divides by nothing useful.
            # Padding the vocabulary is what Megatron does too: the extra rows
            # train to never being predicted and cost a few kilobytes.
            padded = math.ceil(self.vocab_size / self.max_tp) * self.max_tp
            raise ValueError(
                f"vocab_size ({self.vocab_size}) must be divisible by {self.max_tp} for "
                f"vocab-parallel embedding and cross-entropy.\n"
                f"  Pad it to {padded}. Use "
                f"GPTConfig.padded_vocab({self.vocab_size}, {self.max_tp}) or pass "
                f"vocab_size={padded} directly. The extra rows are never predicted."
            )

    @property
    def head_dim(self) -> int:
        return self.n_embd // self.n_head

    @staticmethod
    def padded_vocab(raw_vocab: int, multiple: int = DEFAULT_TP_DEGREE) -> int:
        return math.ceil(raw_vocab / multiple) * multiple

    def with_(self, **changes: Any) -> GPTConfig:
        return replace(self, **changes)


PRESETS: dict[str, dict[str, Any]] = {
    # A common padded vocabulary keeps checkpoint shapes compatible across
    # presets. 72 is the first multiple of 8 above tiny-shakespeare's 65 raw
    # characters; direct max_tp=4 configs need only pad to 68.
    # The default. One CPU rank runs a training step in a few milliseconds.
    # max_tp=4 because four heads split four ways and no further: at tp=8 some
    # rank would own zero heads, and every collective in Lab 2 assumes each
    # rank owns at least one.
    "tiny": dict(n_layer=4, n_head=4, n_embd=128, block_size=128, vocab_size=72, max_tp=4),
    # Big enough that memory numbers get interesting, small enough to still fit
    # four CPU ranks on a laptop.
    "small": dict(n_layer=6, n_head=8, n_embd=384, block_size=256, vocab_size=72, max_tp=8),
    # For the Kaggle 2xT4 notebook, where you have real VRAM to spend.
    "tier2": dict(n_layer=8, n_head=8, n_embd=512, block_size=512, vocab_size=72, max_tp=8),
}


def make_model(preset: str = "tiny", **overrides: Any) -> GPT:
    """Build a preset model. ``make_model("tiny", dropout=0.1)`` works."""
    if preset not in PRESETS:
        raise ValueError(f"unknown preset {preset!r}; choose from {sorted(PRESETS)}")
    return GPT(GPTConfig(**{**PRESETS[preset], **overrides}))


