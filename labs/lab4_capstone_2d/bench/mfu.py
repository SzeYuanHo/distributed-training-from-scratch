#!/usr/bin/env python3
"""Lab 4 deliverable: the configuration table, and MFU where it can be measured.

::

    python tasks.py bench LAB=4

Two things:

1. **The configuration table.** Runs your planner over the default problem on each
   hardware profile and writes the ranked table into
   ``runs/lab4_capstone_2d/config_table.md``. That table is the core of the
   scaling report and it needs no GPUs at all.

2. **MFU**, measured where there is hardware to measure it on. On a laptop that
   means one process on one device, which still tells you what fraction of peak
   your model achieves before any parallelism enters the picture. That single
   number is the ceiling every distributed configuration is a fraction of.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

LAB_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = LAB_DIR.parent.parent
for path in (str(REPO_ROOT), str(LAB_DIR)):
    if path not in sys.path:
        sys.path.insert(0, path)

from common import repo_env  # noqa: E402

repo_env.apply()

import torch  # noqa: E402
import yaml  # noqa: E402

from common import cluster_specs, reference_gpt, timers  # noqa: E402


def measure_single_device_mfu(
    preset: str = "small",
    steps: int = 20,
    batch: int = 8,
    peak_tflops_fp32: float | None = None,
) -> dict:
    """Tokens per second and MFU for one process on one device.

    Model FLOPs per token is ``6*Psi`` for a forward and backward pass: 2 FLOPs per
    parameter per token in the forward, and twice that in the backward, which
    computes both the input gradient and the weight gradient.

    This is **MFU**, not HFU. No recomputation is on, so the two are equal here.
    Turn on activation checkpointing and HFU rises while MFU does not, and that
    gap is the compute you spent to save memory.
    """
    from common import data as data_mod

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dataset = data_mod.load_dataset()

    torch.manual_seed(1337)
    model = reference_gpt.make_model(preset, vocab_size=dataset.vocab_size).to(device)
    optimizer = model.configure_optimizer(lr=1e-3)

    block = model.config.block_size
    start = None

    for step in range(steps):
        x, y = data_mod.get_batch(
            "train", batch_size=batch, block_size=block, step=step, device=device, dataset=dataset
        )
        if step == 5:  # warmup done
            if device.type == "cuda":
                torch.cuda.synchronize()
            start = time.perf_counter()

        _logits, loss = model(x, y)
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

    if device.type == "cuda":
        torch.cuda.synchronize()
    elapsed = time.perf_counter() - start

    measured_steps = steps - 5
    tokens = measured_steps * batch * block
    tokens_per_s = tokens / elapsed

    flops_per_token = model.flops_per_token()
    achieved_flops = tokens_per_s * flops_per_token

    if device.type == "cuda":
        name = torch.cuda.get_device_name(0)
        if peak_tflops_fp32 is not None:
            profile = "user-supplied fp32 peak"
            peak = peak_tflops_fp32 * 1e12
        elif "T4" in name.upper():
            profile = "NVIDIA T4"
            peak = cluster_specs.PROFILES["2xT4 (PCIe 3.0)"]["peak_flops_fp32"]
        else:
            # A model name is not enough to infer a defensible peak: mobile
            # variants, power limits and precision modes can differ materially.
            profile, peak = "unrecognised CUDA device", 0.0
    else:
        profile, peak = "cpu", 0.0

    return {
        "device": device.type,
        "device_name": torch.cuda.get_device_name(0) if device.type == "cuda" else "cpu",
        "profile": profile,
        "n_params": model.num_params(),
        "tokens_per_s": tokens_per_s,
        "flops_per_token": flops_per_token,
        "achieved_flops": achieved_flops,
        "peak_flops": peak,
        "mfu": achieved_flops / peak if peak else 0.0,
    }


def build_config_table(problem_name: str = "default") -> str:
    """Run the planner across every hardware profile and format the tables."""
    from starter import planner

    model = planner.DEFAULT_PROBLEM
    sections = [
        "# Lab 4 configuration table",
        "",
        f"Model: {model.n_params / 1e9:.0f} B parameters, {model.n_layers} layers, "
        f"hidden {model.hidden}, sequence {model.seq_len}, {model.dtype} "
        f"{model.optimizer}, {model.recompute} recomputation.",
        f"Global optimizer-step batch: {model.global_batch_tokens:,} tokens "
        f"({model.global_batch_tokens // model.seq_len:,} complete sequences).",
        "",
        "Generated by `python tasks.py bench LAB=4`. The predictions come from the "
        "cost models in Labs 0 to 3; nothing here was measured.",
        "",
    ]

    for name, spec in cluster_specs.PROFILES.items():
        if spec["n_devices"] < 2:
            continue
        sections.append(f"## {name}")
        sections.append("")
        sections.append("```")
        sections.append(cluster_specs.describe(name))
        sections.append("```")
        sections.append("")

        try:
            configs = planner.enumerate_configs(spec["n_devices"])
            scored = planner.rank_configs(model, configs, spec)
            sections.append(planner.report_table(scored, limit=15))
        except NotImplementedError:
            sections.append("_planner not implemented yet; finish step 3_")
        sections.append("")

    return "\n".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--preset", default="small")
    parser.add_argument("--steps", type=int, default=20)
    parser.add_argument("--batch", type=int, default=8)
    parser.add_argument(
        "--peak-tflops-fp32",
        type=float,
        default=None,
        help="optional theoretical fp32 peak for MFU; unknown GPUs are not guessed",
    )
    parser.add_argument("--nproc", type=int, default=1, help="ignored; kept for the runner")
    args = parser.parse_args(argv)
    if args.peak_tflops_fp32 is not None and args.peak_tflops_fp32 <= 0:
        parser.error("--peak-tflops-fp32 must be positive")

    out_dir = timers.runs_dir("lab4_capstone_2d")

    print("Lab 4: configuration table\n")
    table = build_config_table()
    table_path = out_dir / "config_table.md"
    table_path.write_text(table, encoding="utf-8")
    print(f"  -> {table_path}")

    print("\nLab 4: single-device MFU\n")
    result = measure_single_device_mfu(
        args.preset,
        args.steps,
        args.batch,
        peak_tflops_fp32=args.peak_tflops_fp32,
    )

    print(f"  device            {result['device_name']}")
    print(f"  parameters        {result['n_params'] / 1e6:.2f} M")
    print(f"  tokens/s          {result['tokens_per_s']:,.0f}")
    print(f"  model FLOPs/token {result['flops_per_token'] / 1e6:.2f} M  (6 x params)")
    print(f"  achieved FLOP/s   {result['achieved_flops'] / 1e12:.3f} T")

    if result["peak_flops"]:
        print(f"  peak FLOP/s       {result['peak_flops'] / 1e12:.1f} T ({result['profile']})")
        print(f"  MFU               {result['mfu']:.1%}")
        print()
        print("  Treat this as a workload-specific measurement, not a hardware constant.")
        print("  Small models at short sequence lengths often under-utilise the device")
        print("  because their matrix multiplications are too small to saturate it.")
    else:
        print("  no defensible device peak was selected, so MFU is not reported.")
        print("  On an unrecognised GPU, pass --peak-tflops-fp32 from its specification.")

    summary = {
        "model_flops_per_token_coefficient": {"value": 6, "units": "dimensionless"},
        "measured_tokens_per_s_single_device": {
            "value": result["tokens_per_s"],
            "units": "tokens/s",
        },
    }
    if result["peak_flops"]:
        summary["measured_mfu_single_device"] = {"value": result["mfu"], "units": "fraction"}

    (out_dir / "measurements.yaml").write_text(
        yaml.safe_dump(summary, sort_keys=True), encoding="utf-8"
    )

    print(f"\n  measurements -> {out_dir / 'measurements.yaml'}")
    print("\n  Now write runs/lab4_capstone_2d/scaling_report.md. The template is in")
    print("  the lab's SOLUTION.md. That report is the best artefact in this repo.")
    print("\n  next: python tasks.py reconcile LAB=4")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
